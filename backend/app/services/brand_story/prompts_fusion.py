def get_brand_story_prompt() -> str:
    """获取品牌故事生成器System Prompt"""
    return BRAND_STORY_SYSTEM_PROMPT


def get_brand_story_examples() -> List[Dict[str, str]]:
    """获取品牌故事Few-shot示例"""
    return BRAND_STORY_FEW_SHOT_EXAMPLES


def build_brand_story_messages(
    product_info: Dict[str, str],
    few_shot_limit: int = 2
) -> List[Dict[str, str]]:
    """
    构建品牌故事生成API消息

    Args:
        product_info: 产品信息字典
            - name: 产品名称
            - origin: 产地
            - features: 特点
            - purpose: 用途
            - style: 风格（modern/traditional/emotional）
            - word_count: 字数
        few_shot_limit: Few-shot示例数量（推荐2个）

    Returns:
        消息列表
    """
    # System prompt
    messages = [
        {"role": "system", "content": BRAND_STORY_SYSTEM_PROMPT}
    ]

    # Few-shot examples
    for example in BRAND_STORY_FEW_SHOT_EXAMPLES[:few_shot_limit]:
        messages.append({"role": "user", "content": example["user"]})
        messages.append({"role": "assistant", "content": example["assistant"]})

    # User request
    user_request = f"""产品：{product_info.get('name', '')}；
产地：{product_info.get('origin', '')}；
特点：{product_info.get('features', '')}；
用途：{product_info.get('purpose', '电商详情页')}；
风格：{product_info.get('style', '现代简约')}；
字数：{product_info.get('word_count', '300字左右')}"""

    messages.append({"role": "user", "content": user_request})

    return messages


