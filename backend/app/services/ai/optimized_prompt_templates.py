    @staticmethod
    def validate_context(required_fields: list, provided_context: dict) -> tuple:
        """验证提供的上下文是否完整

        Args:
            required_fields: 必需字段列表
            provided_context: 提供的上下文字典

        Returns:
            (is_valid, missing_fields)
        """
        missing = [f for f in required_fields if f not in provided_context or not provided_context[f]]
        return len(missing) == 0, missing


