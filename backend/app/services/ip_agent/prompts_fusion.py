def build_few_shot_messages(examples: List[Dict[str, str]], limit: int = 3) -> List[Dict[str, str]]:
    """
    构建Few-shot消息列表（用于DeepSeek API调用）

    Args:
        examples: Few-shot示例列表
        limit: 使用的示例数量上限（默认3个，适合DeepSeek）

    Returns:
        消息列表，格式为 [{"role": "user", "content": "..."}, {"role": "assistant", "content": "..."}, ...]
    """
    messages = []
    for example in examples[:limit]:
        messages.append({"role": "user", "content": example["user"]})
        messages.append({"role": "assistant", "content": example["assistant"]})
    return messages


