def build_few_shot_messages(examples: List[Dict[str, str]], limit: int = 3) -> List[Dict[str, str]]:
    """
    构建Few-shot消息列表（用于API调用）

    Args:
        examples: Few-shot示例列表
        limit: 使用的示例数量上限

    Returns:
        消息列表，格式为 [{"role": "user", "content": "..."}, {"role": "assistant", "content": "..."}, ...]
    """
    messages = []
    for example in examples[:limit]:
        messages.append({"role": "user", "content": example["user"]})
        messages.append({"role": "assistant", "content": example["assistant"]})
    return messages


def validate_response(response: str, test_case: Dict) -> Dict[str, any]:
    """
    验证AI响应是否符合测试用例期望

    Args:
        response: AI生成的回复
        test_case: 测试用例字典

    Returns:
        验证结果 {"passed": bool, "missing_features": List[str], "score": float}
    """
    expected = test_case["expected_features"]
    missing = []
    score = 0.0

    for feature in expected:
        # 简单的关键词匹配（生产环境建议用LLM判断）
        if feature.startswith("✓"):
            key_phrase = feature.split("（")[0].replace("✓ ", "")
            if key_phrase in response or any(word in response for word in key_phrase.split("/")):
                score += 1
            else:
                missing.append(feature)
        elif feature.startswith("✗"):
            # 检查不应该出现的内容
            forbidden = feature.replace("✗ 不", "").replace("✗ ", "")
            if forbidden in response:
                missing.append(feature)
            else:
                score += 0.5  # 遵守禁止项得半分

    total_features = len(expected)
    passed = len(missing) == 0
    score_percent = (score / total_features) * 100 if total_features > 0 else 0

    return {
        "passed": passed,
        "missing_features": missing,
        "score": round(score_percent, 2),
        "test_id": test_case["test_id"],
        "scenario": test_case["scenario"]
    }


