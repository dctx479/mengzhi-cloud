def get_live_script_prompt() -> str:
    """获取直播脚本生成器System Prompt"""
    return LIVE_SCRIPT_SYSTEM_PROMPT


def get_live_script_examples() -> List[Dict[str, str]]:
    """获取直播脚本Few-shot示例"""
    return LIVE_SCRIPT_FEW_SHOT_EXAMPLES


def build_live_script_messages(
    product_info: Dict[str, str],
    few_shot_limit: int = 2
) -> List[Dict[str, str]]:
    """
    构建直播脚本生成API消息

    Args:
        product_info: 产品信息字典
            - name: 产品名称
            - scenario: 场景（new_launch/repurchase/clearance/festival）
            - duration: 时长（30min/1hour/2hours）
            - target: 目标
        few_shot_limit: Few-shot示例数量（推荐2个）

    Returns:
        消息列表
    """
    # System prompt
    messages = [
        {"role": "system", "content": LIVE_SCRIPT_SYSTEM_PROMPT}
    ]

    # Few-shot examples
    for example in LIVE_SCRIPT_FEW_SHOT_EXAMPLES[:few_shot_limit]:
        messages.append({"role": "user", "content": example["user"]})
        messages.append({"role": "assistant", "content": example["assistant"]})

    # User request
    scenario_map = {
        "new_launch": "新品首发",
        "repurchase": "爆款复购",
        "clearance": "清仓促销",
        "festival": "节日专场"
    }

    user_request = f"""产品：{product_info.get('name', '')}；
场景：{scenario_map.get(product_info.get('scenario', 'new_launch'), '新品首发')}；
时长：{product_info.get('duration', '1小时')}；
目标：{product_info.get('target', '建立信任，提升转化')}"""

    messages.append({"role": "user", "content": user_request})

    return messages


